export function lookupStudentVerification(query: string): StudentVerification | undefined {
  if (!query) return undefined
  const clean = query.trim().toLowerCase()
  // Exact studentId match
  const byId = STUDENT_VERIFICATION_DATABASE.find(s => s.studentId.toLowerCase() === clean)
  if (byId) return byId

  // Ends with studentId suffix (e.g. searching '1220' or '1116')
  if (clean.length >= 4) {
    const bySuffix = STUDENT_VERIFICATION_DATABASE.find(s => s.studentId.endsWith(clean))
    if (bySuffix) return bySuffix
  }

  // Name match
  const byName = STUDENT_VERIFICATION_DATABASE.find(s => s.studentName.toLowerCase().includes(clean))
  if (byName) return byName

  return undefined
}
